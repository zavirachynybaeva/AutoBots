package com.autobots.java.lambda.lambda;

public class Calculator {

    int sum (int a, int b) {
        return a + b;
    }

    int sub (int a, int b) {
        return a - b;
    }

    int multiple (int a, int b) {
        return a * b;
    }

    int div (int a, int b) {
        return a / b;
    }
}
